/**
 * Checks if an envelope can be opened based on the current date.
 * Rule per user specification:
 * Envelopes are opened day by day after each date passes.
 * For example, when today is November 24, the envelope for November 23 CAN be opened,
 * while the envelope for November 24 CANNOT be opened yet (it unlocks on November 25).
 */
export function isEnvelopeUnlocked(envelope, now = new Date()) {
  const todayStart = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
  const envelopeDateStart = new Date(envelope.year, envelope.month, envelope.day).getTime();
  return envelopeDateStart < todayStart;
}

export function getEnvelopeUnlockDateLabel(envelope) {
  const unlockDate = new Date(envelope.year, envelope.month, envelope.day + 1);
  return unlockDate.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
}
